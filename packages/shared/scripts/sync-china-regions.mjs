import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL =
  'https://raw.githubusercontent.com/modood/Administrative-divisions-of-China/master/dist/pc-code.json';
const SOURCE_REPOSITORY =
  'https://github.com/modood/Administrative-divisions-of-China';
const DIRECT_MUNICIPALITY_CITY_CODES = {
  11: '1101',
  12: '1201',
  31: '3101',
  50: '5001',
};

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputFile = path.resolve(__dirname, '../src/china-region.ts');

function assertString(value, label) {
  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(`Invalid ${label}`);
  }

  return value.trim();
}

function normalizeSourceRegion(rawProvince) {
  const province = {
    code: assertString(rawProvince?.code, 'province code'),
    name: assertString(rawProvince?.name, 'province name'),
    children: [],
  };
  const directCityCode = DIRECT_MUNICIPALITY_CITY_CODES[province.code];

  if (directCityCode) {
    province.children = [
      {
        code: directCityCode,
        name: province.name,
      },
    ];
    return province;
  }

  province.children = (Array.isArray(rawProvince?.children)
    ? rawProvince.children
    : []
  ).map((rawCity) => ({
    code: assertString(rawCity?.code, `${province.name} city code`),
    name: assertString(rawCity?.name, `${province.name} city name`),
  }));

  if (!province.children.length) {
    throw new Error(`Province ${province.name} has no city children`);
  }

  return province;
}

function buildOutput(regions) {
  return `// Generated by packages/shared/scripts/sync-china-regions.mjs.
// Source: ${SOURCE_URL}
// Source repository: ${SOURCE_REPOSITORY}
// Upstream data: 2023 statistical division codes, published 2023-09-11.
// Direct municipalities are collapsed from district-level pc-code children to city-level entries.

export interface ChinaCityRegion {
  code: string;
  name: string;
}

export interface ChinaProvinceRegion {
  code: string;
  name: string;
  children: ChinaCityRegion[];
}

export interface UserRegion {
  countryCode: 'CN';
  countryName: '中国';
  provinceCode: string;
  provinceName: string;
  cityCode: string;
  cityName: string;
}

export const CHINA_REGION_SOURCE = {
  repository: '${SOURCE_REPOSITORY}',
  sourceUrl: '${SOURCE_URL}',
  license: 'WTFPL',
  upstreamVersion: '2023 statistical division codes',
  upstreamCutoffDate: '2023-06-30',
  upstreamPublishedDate: '2023-09-11',
} as const;

export const CHINA_PROVINCE_CITY_REGIONS: ChinaProvinceRegion[] = ${JSON.stringify(
    regions,
    null,
    2
  )};

export function findChinaCityRegion(
  provinceCode: string,
  cityCode: string
): UserRegion | null {
  const normalizedProvinceCode = provinceCode.trim();
  const normalizedCityCode = cityCode.trim();
  const province = CHINA_PROVINCE_CITY_REGIONS.find(
    item => item.code === normalizedProvinceCode
  );
  const city = province?.children.find(item => item.code === normalizedCityCode);

  if (!province || !city) {
    return null;
  }

  return {
    countryCode: 'CN',
    countryName: '中国',
    provinceCode: province.code,
    provinceName: province.name,
    cityCode: city.code,
    cityName: city.name,
  };
}

export function formatUserRegion(region?: UserRegion | null): string {
  if (!region) {
    return '';
  }

  if (region.provinceName === region.cityName) {
    return region.cityName;
  }

  return \`\${region.provinceName} \${region.cityName}\`;
}
`;
}

async function main() {
  const response = await fetch(SOURCE_URL);

  if (!response.ok) {
    throw new Error(`Failed to fetch ${SOURCE_URL}: ${response.status}`);
  }

  const rawRegions = await response.json();

  if (!Array.isArray(rawRegions)) {
    throw new Error('Unexpected china region source shape');
  }

  const regions = rawRegions.map(normalizeSourceRegion);

  await mkdir(path.dirname(outputFile), { recursive: true });
  await writeFile(outputFile, buildOutput(regions));

  const cityCount = regions.reduce(
    (total, province) => total + province.children.length,
    0
  );
  console.log(
    `Wrote ${regions.length} provinces and ${cityCount} cities to ${outputFile}`
  );
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
